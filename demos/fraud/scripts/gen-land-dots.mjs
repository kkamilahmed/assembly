// Precomputes the globe's land dots from Natural Earth (via world-atlas), so
// the app ships a small data file and never fetches anything at runtime.
//   node scripts/gen-land-dots.mjs
// Writes src/scene/globe/landDots.ts: a flat [lat, lon, lat, lon, ...] list
// on an equal-area grid of about STEP degrees.
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';

const STEP = 1.1;
const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-50m.json', import.meta.url)));
const land = feature(topo, topo.objects.land);
const out = [];
for (let lat = -84; lat <= 84; lat += STEP) {
  const step = STEP / Math.max(Math.cos((lat * Math.PI) / 180), 0.08);
  // Stagger alternate rows so the grid reads as dots, not stripes.
  const row = Math.round((lat + 84) / STEP);
  for (let lon = -180 + (row % 2) * step * 0.5; lon < 180; lon += step) {
    if (geoContains(land, [lon, lat])) out.push(Math.round(lat * 10) / 10, Math.round(lon * 10) / 10);
  }
}
const body = `// Generated by scripts/gen-land-dots.mjs from Natural Earth 1:50m land
// (world-atlas). Do not edit by hand. Flat [lat, lon, ...] in degrees.
export const LAND_DOTS: readonly number[] = [${out.join(',')}];
`;
writeFileSync(new URL('../src/scene/globe/landDots.ts', import.meta.url), body);
console.log('dots', out.length / 2, 'bytes', body.length);
